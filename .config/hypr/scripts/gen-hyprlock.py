#!/usr/bin/env python3
"""Generate ~/.config/hypr/hyprlock.conf — the DUNE title-card lockscreen — with per-monitor sizing.

hyprlock has no automatic "make it bigger on a small dense screen" knob, so every widget is
emitted once per monitor with its sizes multiplied by that monitor's factor.
Edit MONITORS (or the design below) and re-run:   python3 ~/.config/hypr/scripts/gen-hyprlock.py
"""
from pathlib import Path

# monitor name -> size factor   (laptop panel is physically small: scale it up)
MONITORS = {
    "eDP-1": 1.4,
    "HDMI-A-1": 1.0,
    "DP-1": 1.0,
    "DP-2": 1.0,
}

HEADER = """# ───────────────────────────────────────────────────────────────
#  D U N E  —  lockscreen as a cinematic title card
#  GENERATED by scripts/gen-hyprlock.py — edit that, not this file.
# ───────────────────────────────────────────────────────────────

$sand  = rgba(234, 197, 178, 1.0)
$sandD = rgba(234, 197, 178, 0.6)
$spice = rgba(217, 138, 78, 1.0)
$night = rgba(13, 11, 10, 1.0)
$font  = Lexend Peta

general {
    hide_cursor = true
    grace = 0
    ignore_empty_input = true
}

animations {
    enabled = true
    bezier = haze, 0.45, 0, 0.25, 1
    animation = fadeIn, 0                 # instant: a slow fade-in shows the desktop for ~1s after waking from sleep
    animation = fadeOut, 1, 6, haze
    animation = inputFieldDots, 1, 3, haze
}

background {
    monitor =
    path = /home/gopal/.config/hypr/wallpapers/dune_lock.jpg
    blur_passes = 2
    blur_size = 4
    noise = 0.04
    brightness = 0.75
    contrast = 1.0
    vibrancy = 0.1
}
"""


def widgets(mon: str, k: float) -> str:
    r = lambda v: int(round(v * k))  # noqa: E731
    ls = lambda v: int(round(v * k))  # pango letter_spacing (1/1024 pt)  # noqa: E731
    return f"""
# ════════════════ {mon}  (×{k}) ════════════════

# letterbox
shape {{
    monitor = {mon}
    size = 8000, {r(110)}
    color = $night
    rounding = 0
    zindex = 0
    position = 0, 0
    halign = center
    valign = top
}}
shape {{
    monitor = {mon}
    size = 8000, {r(110)}
    color = $night
    rounding = 0
    zindex = 0
    position = 0, 0
    halign = center
    valign = bottom
}}

# clock
label {{
    monitor = {mon}
    zindex = 10
    text = cmd[update:1000] echo "<span letter_spacing='{ls(40000)}'>$(date +%H)  $(date +%M)</span>"
    color = $sand
    font_size = {r(92)}
    font_family = $font Thin
    position = 0, {r(170)}
    halign = center
    valign = center
    shadow_passes = 3
    shadow_size = 6
    shadow_color = rgba(0, 0, 0, 0.5)
}}

# eclipse flare
shape {{
    monitor = {mon}
    zindex = 10
    size = {r(720)}, 1
    color = rgba(234, 197, 178, 0.45)
    rounding = 0
    position = 0, {r(70)}
    halign = center
    valign = center
}}
shape {{
    monitor = {mon}
    zindex = 10
    size = {r(220)}, {max(1, r(1))}
    color = rgba(255, 240, 230, 0.9)
    rounding = 0
    position = 0, {r(70)}
    halign = center
    valign = center
}}
shape {{
    monitor = {mon}
    zindex = 10
    size = {r(11)}, {r(11)}
    color = rgba(10, 10, 14, 1.0)
    rounding = -1
    border_size = {max(2, r(2))}
    border_color = rgba(255, 244, 236, 1.0)
    position = 0, {r(70)}
    halign = center
    valign = center
    shadow_passes = 3
    shadow_size = {r(10)}
    shadow_color = rgba(255, 220, 190, 0.9)
}}

# date
label {{
    monitor = {mon}
    zindex = 10
    text = cmd[update:60000] echo "<span letter_spacing='{ls(9000)}'>$(date '+%A   ·   %d %B' | tr a-z A-Z)</span>"
    color = $spice
    font_size = {r(13)}
    font_family = $font Light
    position = 0, {r(28)}
    halign = center
    valign = center
}}

# password
input-field {{
    monitor = {mon}
    zindex = 10
    size = {r(420)}, {r(44)}
    outline_thickness = 1
    rounding = 0
    dots_size = 0.18
    dots_spacing = 0.9
    dots_center = true
    dots_rounding = -1
    dots_text_format = ◆
    inner_color = rgba(13, 11, 10, 0.35)
    outer_color = rgba(234, 197, 178, 0.35)
    check_color = rgba(217, 138, 78, 0.9)
    fail_color = rgba(224, 86, 59, 0.95)
    capslock_color = rgba(142, 201, 255, 0.9)
    font_color = $sand
    font_family = $font Light
    fade_on_empty = false
    placeholder_text = <span letter_spacing="{ls(6000)}" foreground="##eac5b299">THE SLEEPER MUST AWAKEN</span>
    fail_text = <span letter_spacing="{ls(6000)}">ACCESS DENIED · $ATTEMPTS</span>
    fail_timeout = 2500
    position = 0, {r(-90)}
    halign = center
    valign = center
}}

# lower letterbox: litany · place · power
label {{
    monitor = {mon}
    zindex = 10
    text = <span letter_spacing="{ls(7000)}">FEAR IS THE MIND-KILLER</span>
    color = $sandD
    font_size = {r(9)}
    font_family = $font Light
    position = {r(60)}, {r(46)}
    halign = left
    valign = bottom
}}
label {{
    monitor = {mon}
    zindex = 10
    text = cmd[update:30000] echo "<span letter_spacing='{ls(7000)}'>ARRAKIS  ·  $(whoami | tr a-z A-Z)  ·  $(cat /sys/class/power_supply/BAT*/capacity 2>/dev/null | head -1)%</span>"
    color = $sandD
    font_size = {r(9)}
    font_family = $font Light
    position = {r(-60)}, {r(46)}
    halign = right
    valign = bottom
}}

# upper letterbox: keyboard layout
label {{
    monitor = {mon}
    zindex = 10
    text = <span letter_spacing="{ls(7000)}">$LAYOUT</span>
    color = rgba(234, 197, 178, 0.4)
    font_size = {r(8)}
    font_family = $font Light
    position = 0, {r(-48)}
    halign = center
    valign = top
}}
"""


out = HEADER + "".join(widgets(m, k) for m, k in MONITORS.items())
Path(__file__).resolve().parent.parent.joinpath("hyprlock.conf").write_text(out)
print("wrote hyprlock.conf for", ", ".join(f"{m}×{k}" for m, k in MONITORS.items()))
